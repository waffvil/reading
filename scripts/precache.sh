#!/bin/sh
# Regenerates precache.js — every file the service worker stores at install so the app works offline.
# Run after changing vendor/ or adding top-level files, then bump VERSION in sw.js.
cd "$(dirname "$0")/.." || exit 1
{
  echo "// generated by scripts/precache.sh — do not edit"
  echo "self.PRECACHE = ["
  for f in index.html app.css app.js manifest.json icon-180.png icon-192.png icon-512.png \
           vendor/pdfjs/pdf.min.mjs vendor/pdfjs/pdf.worker.min.mjs; do echo "  \"$f\","; done
  find vendor/pdfjs/standard_fonts vendor/pdfjs/cmaps -type f | sort | sed 's/.*/  "&",/'
  echo "];"
} > precache.js
echo "precache.js: $(grep -c '"' precache.js) files"
